package scoop

import (
	"errors"
	"slices"
	"strings"
	"time"
)

// ListApp scoop list 表格中的一行（已安装应用）
type ListApp struct {
	Name    string
	Version string
	Source  string // bucket 名（也可能是 URL / <auto-generated>）
	Updated time.Time
	Info    string // Deprecated package / Held package 等附加信息，可为空
}

// ListInstalledApps 执行 scoop list，返回按更新时间升序排列的全部已安装应用
// （最久未更新的在最前）。与 update 等命令的流式透传不同：全量捕获输出后统一
// 解析、排序，再交调用方输出
func ListInstalledApps() ([]ListApp, error) {
	s, err := runScoop("list")
	if err != nil {
		return nil, err
	}

	apps, err := parseListApps(s)
	if err != nil {
		return nil, err
	}
	sortListApps(apps)
	return apps, nil
}

// parseListApps 解析 scoop list 的表格输出。
// 非空行依次为标题（Installed apps:）、列名行、分隔线，其余为数据行。
// 按分隔线确定各列起始位置，据此切分每行数据（与 status -l 的解析同法）
func parseListApps(s string) ([]ListApp, error) {
	var nonEmpty []string
	for line := range strings.SplitSeq(s, "\n") {
		line = strings.TrimSpace(line)
		if line != "" {
			nonEmpty = append(nonEmpty, line)
		}
	}
	if len(nonEmpty) < 3 { // 至少要有标题、列名行和分隔线
		return nil, errors.New("scoop list 输出缺少标题行或分隔线")
	}

	starts := findColumnStarts(nonEmpty[2])
	if len(starts) < 5 {
		return nil, errors.New("scoop list 分隔线列数不足 5，无法解析")
	}

	var apps []ListApp
	for _, line := range nonEmpty[3:] {
		apps = append(apps, parseListApp(line, starts))
	}
	return apps, nil
}

// parseListApp 按列起始位置切分一行，返回 ListApp 结构体
func parseListApp(line string, starts []int) ListApp {
	length := len(line)

	cut := func(a, b int) string { // 从行字符串中，按起止位置切分段落的闭包
		if a >= length {
			return ""
		}
		end := min(b, length)
		if a >= end {
			return ""
		}

		return strings.TrimSpace(line[a:end])
	}

	// Updated 为本地时间（scoop 取 install.json 的 LastWriteTime），
	// 无法解析时保持零值，排序时视为最旧
	updated, _ := time.ParseInLocation(time.DateTime, cut(starts[3], starts[4]), time.Local)

	return ListApp{
		Name:    cut(starts[0], starts[1]),
		Version: cut(starts[1], starts[2]),
		Source:  cut(starts[2], starts[3]),
		Updated: updated,
		Info:    cut(starts[4], length),
	}
}

// sortListApps 按更新时间升序排列（最久未更新的在前），时间相同按名称字母序定序
func sortListApps(apps []ListApp) {
	slices.SortFunc(apps, func(a, b ListApp) int {
		if c := a.Updated.Compare(b.Updated); c != 0 {
			return c
		}
		return strings.Compare(strings.ToLower(a.Name), strings.ToLower(b.Name))
	})
}
